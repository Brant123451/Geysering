def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--mesh-generator",
        choices=("cartesian", "snappy"),
        default="cartesian",
        help="strict-quality cfMesh Cartesian mesh or the retained snappyHexMesh sensitivity",
    )
    parser.add_argument("--mesh-profile", choices=("base", "refined"), default="base")
    parser.add_argument(
        "--pocket-profile",
        choices=("pocket_small", "base", "pocket_large"),
        default="base",
    )
    parser.add_argument(
        "--interface-solver",
        choices=("mules", "iso-advector"),
        default="mules",
        help="VOF transport algorithm; both choices retain compressible energy/EOS physics",
    )
    parser.add_argument("--air-cp", type=float)
    parser.add_argument("--water-bulk-modulus", type=float)
    parser.add_argument(
        "--turbulence-model",
        choices=("laminar", "kOmegaSST"),
        help="override the declared production turbulence closure",
    )
    parser.add_argument("--gate-area", type=float)
    parser.add_argument("--contact-angle", type=float)
    parser.add_argument("--c-alpha", type=float)
    parser.add_argument(
        "--thin-layer-cell-size",
        type=float,
        help=(
            "override only the cfMesh crown-layer cell size; used to isolate "
            "thin-layer resolution from the full refined-mesh profile"
        ),
    )
    parser.add_argument(
        "--velocity-limit",
        type=float,
        default=0.0,
        help=(
            "optional diagnostic maximum |U| in m/s; 0 keeps the production "
            "case free of velocity clipping"
        ),
    )
    parser.add_argument("--max-co", type=float, default=0.35)
    parser.add_argument("--max-alpha-co", type=float, default=0.20)
    parser.add_argument("--max-dt", type=float, default=0.0005)
    parser.add_argument("--np", type=int, default=4)
    args = parser.parse_args()
    metadata = generate(args)
    print(json.dumps(metadata, indent=2))


if __name__ == "__main__":
    main()
