    ramp = model["ramp_start_solver_s"]
    q0 = paper["initial_flow_m3_s"]
    q1 = paper["final_flow_m3_s"]
    ramp_end = ramp + paper["flow_ramp_s"]
    top = paper["chamber_height_m"] + paper["riser_length_m"] + model["plume_height_above_rim_m"]
